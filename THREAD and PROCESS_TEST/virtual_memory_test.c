#include<stdio.h>
#include<unistd.h>   // fork() / sleep()

int main()
{
  int val=123;         // 局部变量: 分配在用户栈的栈帧里
  //定义变量接受子进程 

  __pid_t pid ;        // 接住 fork() 的返回值: 父进程>0(子进程PID), 子进程=0, 失败=-1
  //创建一个子进程: 底层是 clone(不带 CLONE_VM), 子进程复制父进程的地址空间
  if((pid=fork())>0)
  {
    sleep(1);        // 让子进程先跑, 打印顺序更直观(与内存独立性无关)

    printf("父进程中的val=%d,val所在的地址为%p\n",val,&val);   // %p 打印的是虚拟地址(完整 64 位)

  }
  else if(pid==0)
  {
    val=321;         // 子进程第一次写这一页 -> 触发写时复制(COW), 内核给它拷贝一份新物理页
    printf("子进程中的val=%d,val所在的地址为%p\n",val,&val);   // 同一虚拟地址, 但指向子进程自己的物理页

  }
  else 
  {
    printf("子进程创建失败\n");
  }

  return 0;
}
//父子进程中各自打印了val变量的值和内存地址。子进程将val变量更改为321，我们特意让父进程休眠了一秒，确保子进程的更改先于父进程的输出。
//我们发现子进程修改了val变量的值，而父进程的val未受影响，说明两个进程的val变量是完全独立的。但是，二者的内存地址却完全相同。
//
//为什么?
//① 打印的是虚拟地址, 不是物理地址: 每个进程有自己的页表, &val 只是虚拟地址空间里的坐标
//   (可用 /proc/PID/maps 验证: 它落在本进程的 [stack] 区间)。
//② 地址相同: fork 时子进程复制了父进程的地址空间布局(页表逐项复制), val 的虚拟地址必然一样。
//③ 值独立: 同一虚拟地址在父子的页表里指向不同物理页。子进程写 val=321 触发 COW:
//   内核分配新物理页、拷贝内容、改页表。此后各改各的。(实测: 该写操作恰好引发 1 次缺页)